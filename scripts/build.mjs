#!/usr/bin/env node
/* Freelance Ledger build step. Zero dependencies. Run from anywhere:  node scripts/build.mjs
   It is idempotent and safe to re-run. It:
   1. writes aff-data.js from affiliates.json (only live affiliate URLs are exposed)
   2. rewrites every <a data-aff="key"> to the tracking URL (+ sponsored rel) or the plain vendor URL
   3. shows/hides the affiliate disclosure banner and "(affiliate link)" labels per page
   4. shows/hides the own-product (Gumroad) box
   5. prerenders the tools grid + filter buttons into index.html (so crawlers see them without JS)
   6. regenerates sitemap.xml (lastmod comes from each page's JSON-LD dateModified)
*/
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://www.getfreelanceledger.com';
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const write = (f, s) => fs.writeFileSync(path.join(ROOT, f), s);

const AFFS = JSON.parse(read('affiliates.json'));
const isLive = (k) => !!(AFFS[k] && AFFS[k].live && AFFS[k].url);
const liveMap = {};
for (const k of Object.keys(AFFS)) if (!k.startsWith('_') && isLive(k) && k !== 'gumroad-templates') liveMap[k] = AFFS[k].url;

// 1. aff-data.js
write('aff-data.js', `/* GENERATED by scripts/build.mjs from affiliates.json. Do not edit. */\nconst AFF=${JSON.stringify(liveMap)};\n`);

// 2-4. per-page rewrites
const htmlFiles = fs.readdirSync(ROOT).filter((f) => f.endsWith('.html'));
const attr = (s) => s.replace(/&(?!amp;)/g, '&amp;');
let changed = 0;
for (const f of htmlFiles) {
  let h = read(f);
  const orig = h;
  let liveCount = 0;
  h = h.replace(/<a\b[^>]*\bdata-aff="([a-z0-9-]+)"[^>]*>(.*?)<\/a>(<span data-aff-label[^>]*>(.*?)<\/span>)?/gs, (m, key, text, _lab, labText) => {
    const e = AFFS[key];
    if (!e) throw new Error(`${f}: unknown affiliate key "${key}" (add it to affiliates.json)`);
    const live = isLive(key);
    if (live) liveCount++;
    const href = attr(live ? e.url : e.vendor);
    const a = `<a data-aff="${key}" href="${href}" target="_blank" rel="${live ? 'sponsored nofollow noopener' : 'noopener'}">${text}</a>`;
    return a + (labText !== undefined ? `<span data-aff-label${live ? '' : ' hidden'}>${labText}</span>` : '');
  });
  h = h.replace(/<p class="disc"([^>]*?)data-aff-disc([^>]*)>/g, (m, a, b) => {
    const clean = (a + b).replace(/\s*\bhidden\b/g, '');
    return `<p class="disc"${clean.replace(/\s+$/, '')} data-aff-disc${liveCount ? '' : ' hidden'}>`;
  });
  const own = isLive('gumroad-templates');
  h = h.replace(/<div class="own" data-own="gumroad-templates"( hidden)?>/g, `<div class="own" data-own="gumroad-templates"${own ? '' : ' hidden'}>`);
  if (own) h = h.replace(/(<a class="btn" data-own-link="gumroad-templates" href=")[^"]*(")/g, (m, a, b) => a + attr(AFFS['gumroad-templates'].url) + b);
  if (h !== orig) { write(f, h); changed++; }
}

// 5. prerender tools grid
const ctx = vm.createContext({ AFF: liveMap });
const api = vm.runInContext(read('tools.js') + '\n;({TOOLS,cardHtml})', ctx);
const cats = ['all', ...new Set(api.TOOLS.map((t) => t[2]))];
const filters = cats.map((c) => `<button type="button" class="${c === 'all' ? 'on' : ''}" data-c="${c}" aria-pressed="${c === 'all'}">${c}</button>`).join('');
const cards = api.TOOLS.map(api.cardHtml).join('');
let idx = read('index.html');
const before = idx;
idx = idx.replace(/(<nav id="filters" aria-label="Filter tools by category">)[\s\S]*?(<\/nav>)/, (m, a, b) => a + filters + b);
idx = idx.replace(/(<div id="grid">)[\s\S]*?(<\/div><!--\/grid-->)/, (m, a, b) => a + cards + b);
if (idx !== before) { write('index.html', idx); changed++; }

// 6. sitemap
const skip = new Set(['404.html']);
const pages = htmlFiles.filter((f) => !skip.has(f));
const prio = (f) => (f === 'index.html' ? '1.0' : /calculator|template|due-dates/.test(f) ? '0.8' : f === 'privacy.html' ? '0.2' : '0.7');
const urls = pages.sort((a, b) => (a === 'index.html' ? -1 : b === 'index.html' ? 1 : a.localeCompare(b))).map((f) => {
  const h = read(f);
  const m = h.match(/"dateModified":"(\d{4}-\d{2}-\d{2})"/);
  const loc = f === 'index.html' ? `${SITE}/` : `${SITE}/${f}`;
  return { f, loc, last: m ? m[1] : '' };
});
const newest = urls.map((u) => u.last).sort().pop();
const urlXml = urls.map((u) => `  <url><loc>${u.loc}</loc>${(u.last || newest) ? `<lastmod>${u.last || newest}</lastmod>` : ''}<priority>${prio(u.f)}</priority></url>`);
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urlXml.join('\n')}\n</urlset>\n`);

console.log(`build ok: ${htmlFiles.length} pages, ${Object.keys(liveMap).length} live affiliate link(s), ${changed} file(s) updated, ${urls.length} sitemap URLs`);
